CREATE DATABASE IF NOT EXISTS flight_booking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE flight_booking;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('CUSTOMER','ADMIN') NOT NULL DEFAULT 'CUSTOMER',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS flights (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 flight_number VARCHAR(20) NOT NULL UNIQUE,
 airline VARCHAR(80) NOT NULL,
 origin VARCHAR(100) NOT NULL,
 destination VARCHAR(100) NOT NULL,
 departure_at DATETIME NOT NULL,
 arrival_at DATETIME NOT NULL,
 price DECIMAL(10,2) NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 total_seats INT UNSIGNED NOT NULL,
 available_seats INT UNSIGNED NOT NULL,
 status ENUM('SCHEDULED','CANCELLED') NOT NULL DEFAULT 'SCHEDULED',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_flight_search (origin,destination,departure_at,status)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 booking_reference VARCHAR(20) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 flight_id BIGINT UNSIGNED NOT NULL,
 passenger_count INT UNSIGNED NOT NULL,
 total_amount DECIMAL(10,2) NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 status ENUM('CONFIRMED','CANCELLED') NOT NULL DEFAULT 'CONFIRMED',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_booking_user FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT fk_booking_flight FOREIGN KEY(flight_id) REFERENCES flights(id),
 INDEX idx_booking_user(user_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS passengers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 booking_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL,
 passport_number VARCHAR(40) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_passenger_booking FOREIGN KEY(booking_id) REFERENCES bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB;

